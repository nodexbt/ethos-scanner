-- Base schema: the tables the app and scripts read before any dated
-- migration in this folder runs. Reconstructed from the production
-- database (the originals were created by hand in the Supabase SQL
-- editor). Run this first on a fresh project, then every dated file in
-- name order.
--
-- Idempotent — re-running is safe. Run via Supabase SQL editor.

-- One row per scanned Ethos profile (or raw wallet). cluster_result holds
-- the full serialized ClusterScanResult; the dated migrations add the
-- generated strong_count / possible_count columns and profile_id.
CREATE TABLE IF NOT EXISTS investigations (
  id                          text PRIMARY KEY,        -- scan-p<profileId> or scan-0x<address>
  target                      text NOT NULL,
  target_name                 text,
  target_avatar               text,
  cluster_result              jsonb NOT NULL,
  ai_analysis                 text,
  share_id                    text UNIQUE,
  is_public                   boolean NOT NULL DEFAULT false,
  owner_profile_id            integer,
  last_scanned_by_profile_id  integer,
  scan_duration_ms            integer,                 -- feeds the ETA baseline
  twitter_evidence            jsonb,
  created_at                  timestamptz NOT NULL DEFAULT now(),
  updated_at                  timestamptz NOT NULL DEFAULT now()
);

-- Manual access overrides, with an audit trail. Everyone else gets in via
-- lib/access.ts (human-verified + score, or validator NFT).
CREATE TABLE IF NOT EXISTS allowed_users (
  profile_id        bigint PRIMARY KEY,
  added_by          bigint NOT NULL,
  added_at          timestamptz NOT NULL DEFAULT now(),
  note              text,
  twitter_username  text,
  display_name      text,
  avatar_url        text
);

CREATE TABLE IF NOT EXISTS allowed_users_audit (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_id        bigint NOT NULL,
  action            text NOT NULL,                     -- add | remove | edit
  actor_profile_id  bigint NOT NULL,
  details           jsonb,
  created_at        timestamptz NOT NULL DEFAULT now()
);

-- Read-only mirror of Ethos profiles, refreshed daily by
-- scripts/sync/profile-mirror.ts. Lets a scan map counterparty wallets to
-- profiles with one local query instead of thousands of API calls.
CREATE TABLE IF NOT EXISTS profile_latest (
  profile_id                integer PRIMARY KEY,
  score                     integer,
  xp_total                  bigint,
  human_verified            boolean,
  display_name              text,
  username                  text,
  avatar_url                text,
  primary_address           text,
  market_lifetime_bought_wei numeric DEFAULT 0,
  market_lifetime_sold_wei   numeric DEFAULT 0,
  market_open_value_wei      numeric DEFAULT 0,
  last_seen                 timestamptz NOT NULL DEFAULT now(),
  created_at                timestamptz NOT NULL DEFAULT now()
);

-- Every wallet attested to a profile. is_contract is added by
-- 2026-07-03-wallet-is-contract.sql.
CREATE TABLE IF NOT EXISTS profile_addresses (
  profile_id  integer NOT NULL,
  address     text NOT NULL,                           -- lowercase 0x…
  created_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (profile_id, address)
);
CREATE INDEX IF NOT EXISTS profile_addresses_address_idx ON profile_addresses (address);

-- Per-user watchlist; notifications are added by 2026-10-23-notifications.sql.
CREATE TABLE IF NOT EXISTS watchlist (
  user_profile_id     integer NOT NULL,
  watched_profile_id  integer NOT NULL,
  note                text,
  added_at            timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_profile_id, watched_profile_id)
);

-- One row per profile-mirror sync run.
CREATE TABLE IF NOT EXISTS monitoring_runs (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  started_at     timestamptz NOT NULL DEFAULT now(),
  finished_at    timestamptz,
  status         text NOT NULL DEFAULT 'running',       -- running | success | error
  rows_written   integer,
  error_message  text,
  duration_ms    integer
);

NOTIFY pgrst, 'reload schema';
